BUNDLES = {"ru": RU, "en": EN}


def norm(lang: str | None) -> str:
    lang = (lang or "").split("-", 1)[0].lower()
    return lang if lang in SUPPORTED else DEFAULT


def bundle(lang: str | None) -> dict:
    lang = norm(lang)
    out = dict(RU)
    out.update(BUNDLES.get(lang, {}))
    return out


def tr(lang: str | None, key: str, **kw) -> str:
    s = bundle(lang).get(key, key)
    return s.format(**kw) if kw else s
